"""Install the local package and enable task evidence in one project."""

import argparse
import ast
import json
import os
from pathlib import Path
import re
import shlex
import stat
import subprocess
import sys
import tempfile

from auto_eval_session_notice import INSTRUCTION_END, INSTRUCTION_START

ENTRYPOINT_MARKER = "# Generated by agent_level bootstrap.py"
IMPORT_START = "<!-- agent-level:task-evidence-import:start -->"
IMPORT_END = "<!-- agent-level:task-evidence-import:end -->"
IMPORT_HEADER = ("## agent_level: automatic task evidence\n\n"
                 "Read and follow the task evidence workflow in:\n")
COMMANDS_HEADER = ("\n## agent_level: installed commands\n\n"
                   "Use these commands without activating a virtual environment:\n")
PUBLIC_COMMANDS = ('agent-level', 'agent-level-record', 'agent-level-session-notice')


def write_text(path, content):
    if path.is_symlink():
        raise ValueError(f"refusing to replace symlink: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        if path.exists():
            os.fchmod(fd, stat.S_IMODE(path.stat().st_mode))
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(content)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def enable_instructions(workspace, source, *, instructions=None):
    instructions = instructions or source / "AGENTS.md"
    source_text = instructions.read_text(encoding="utf-8")
    start = source_text.find(INSTRUCTION_START)
    end = source_text.find(INSTRUCTION_END, start)
    if start < 0 or end < 0:
        raise ValueError("task evidence section is missing from source AGENTS.md")
    section = f"{IMPORT_HEADER}@{instructions}\n"
    agents = workspace / "AGENTS.md"
    if agents.is_symlink():
        raise ValueError(f"refusing to replace symlink: {agents}")
    current = agents.read_text(encoding="utf-8") if agents.exists() else ""
    reference = re.search(
        rf"(?m)^{re.escape(IMPORT_HEADER)}@[^\n]+\n?"
        rf"(?:{re.escape(COMMANDS_HEADER)}- Recorder: [^\n]+\n- Report: [^\n]+\n)?", current)
    opening, closing = INSTRUCTION_START, INSTRUCTION_END
    if IMPORT_START in current or IMPORT_END in current:
        opening, closing = IMPORT_START, IMPORT_END
    # Enabling this checkout must preserve the canonical instructions themselves.
    if agents == instructions:
        updated = current
    elif opening in current or closing in current:
        old_start = current.find(opening)
        old_end = current.find(closing, old_start)
        if old_start < 0 or old_end < 0:
            raise ValueError(f"incomplete task evidence section: {agents}")
        suffix = current[old_end + len(closing):].removeprefix("\n")
        updated = current[:old_start] + section + suffix
    elif reference:
        updated = current[:reference.start()] + section + current[reference.end():]
    else:
        legacy = (r"(?m)^## Automatic Task Evidence\n\n"
                  r"For substantive engineering tasks, follow "
                  r"\[task evidence instructions\]\([^\n)]*AUTO_EVALUATION\.md\)\.\n?")
        clean = re.sub(legacy, "", current).strip()
        updated = clean + "\n\n" + section if clean else section
    if updated != current:
        write_text(agents, updated)
    claude = workspace / "CLAUDE.md"
    if claude.is_symlink():
        raise ValueError(f"refusing to replace symlink: {claude}")
    current = claude.read_text(encoding="utf-8") if claude.exists() else ""
    if "@AGENTS.md" not in (line.strip() for line in current.splitlines()):
        write_text(claude, current.rstrip() + "\n\n@AGENTS.md\n" if current else "@AGENTS.md\n")


def is_notice_command(command):
    """Recognize our executable, without matching arbitrary shell snippets."""
    if not isinstance(command, str):
        return False
    try:
        argv = shlex.split(command)
    except ValueError:
        return False
    return ((len(argv) == 1 and Path(argv[0]).name == "agent-level-session-notice")
            or (len(argv) == 2 and re.fullmatch(r"python(?:\d+(?:\.\d+)*)?", Path(argv[0]).name)
                and Path(argv[1]).name == "auto_eval_session_notice.py"))


def enable_hook(path, command):
    if path.is_symlink():
        raise ValueError(f"refusing to replace symlink: {path}")
    current = path.read_text(encoding="utf-8") if path.exists() else "{}"
    data = json.loads(current)
    if not isinstance(data, dict):
        raise ValueError(f"invalid hook settings: {path}")
    hooks = data.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise ValueError(f"invalid hook settings: {path}")
    startup = hooks.setdefault("SessionStart", [])
    if not isinstance(startup, list):
        raise ValueError(f"invalid hook settings: {path}")
    found = False
    for entry in startup:
        if not isinstance(entry, dict):
            continue
        items = entry.get("hooks", [])
        if not isinstance(items, list):
            raise ValueError(f"invalid hook settings: {path}")
        for item in items:
            if not isinstance(item, dict):
                continue
            configured = item.get("command")
            if item.get("type") == "command" and is_notice_command(configured):
                item["command"] = command
                found = True
    if not found:
        startup.append({"matcher": "startup", "hooks": [
            {"type": "command", "command": command, "timeout": 5}]})
    if data != json.loads(current):
        write_text(path, json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def assess_entrypoint_content(venv):
    """Exact old launcher template, used only to remove unmodified generated files."""
    command = str(venv / "bin" / "agent-level-assess")
    return f'''#!/usr/bin/env python3
{ENTRYPOINT_MARKER}
import os
from pathlib import Path
import sys

command = {command!r}
args = sys.argv[1:]
if not any(arg in ("--project-dir", "--eval-results") or
           arg.startswith(("--project-dir=", "--eval-results=")) for arg in args):
    args = ["--project-dir", str(Path(__file__).resolve().parent), *args]
os.execv(command, [command, *args])
'''


def remove_generated_entrypoints(project_dir):
    for name in ("agent_level_assess.py", "assess.py"):
        path = project_dir / name
        if path.is_symlink() or not path.is_file():
            continue
        content = path.read_text(encoding="utf-8")
        if ENTRYPOINT_MARKER not in content.splitlines()[:3]:
            continue
        command_lines = [line.removeprefix("command = ") for line in content.splitlines()
                         if line.startswith("command = ")]
        if len(command_lines) != 1:
            continue
        try:
            command = ast.literal_eval(command_lines[0])
        except (SyntaxError, ValueError):
            continue
        if not isinstance(command, str) or not Path(command).is_absolute() or Path(command).name != "agent-level-assess":
            continue
        if content == assess_entrypoint_content(Path(command).parent.parent):
            path.unlink()


def enable_workspace(workspace, venv, source, *, instructions=None):
    workspace = Path(workspace).expanduser().resolve(strict=True)
    source = Path(source).resolve(strict=True)
    venv = Path(venv).expanduser().resolve(strict=True)
    if not workspace.is_dir() or not (instructions or source / "AGENTS.md").is_file():
        raise ValueError("workspace or task evidence instructions are missing")
    command = shlex.quote(str(venv / "bin" / "agent-level-session-notice"))
    enable_instructions(workspace, source, instructions=instructions)
    enable_hook(workspace / ".codex" / "hooks.json", command)
    enable_hook(workspace / ".claude" / "settings.json", command)
    remove_generated_entrypoints(workspace)


def install_package(source, venv):
    python = venv / "bin" / "python"
    if not venv.exists():
        subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
    elif not python.is_file():
        raise ValueError(f"not a Python venv: {venv}")
    pip = [str(python), "-m", "pip", "install"]
    backend = subprocess.run([str(python), "-c",
                              "from setuptools.build_meta import build_editable; import wheel"],
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if backend.returncode == 0:
        pip.extend(["--no-build-isolation", "--no-deps"])
    subprocess.run(pip + ["-e", str(source)], check=True)


def setup_main(argv=None):
    """Public setup uses the active installation, including a standalone wheel."""
    return main(argv, public=True)


def report_command(workspace, venv):
    return shlex.join([str(venv / 'bin' / 'agent-level'), '--project-dir', str(workspace)])


def commands_available(venv):
    return all((venv / 'bin' / name).is_file() for name in PUBLIC_COMMANDS)


def main(argv=None, *, public=False):
    parser = argparse.ArgumentParser(
        prog="agent-level setup" if public else None,
        description="Install Agent Level if needed and enable task recording in one step.")
    parser.add_argument("--project-dir", type=Path, nargs="?", const=Path("."),
                        default=Path("."), help="default: current directory")
    parser.add_argument("--venv", type=Path, help=(
        "default: active venv, else existing project/venv or project/.venv" if public else
        "default: existing project/venv, else project/.venv"))
    args = parser.parse_args(argv)
    try:
        workspace = args.project_dir.expanduser().resolve(strict=True)
        if not workspace.is_dir():
            raise ValueError("project directory must be a directory")
        source = Path(__file__).resolve().parent
        checkout = (source / "pyproject.toml").is_file() and (source / "AGENTS.md").is_file()
        instructions = source / "AGENTS.md" if checkout else source / "assessment" / "task_evidence.md"
        active_venv = Path(sys.prefix) if public and sys.prefix != sys.base_prefix else None
        venv = args.venv or active_venv or (workspace / "venv" if (workspace / "venv").exists()
                             else workspace / ".venv")
        venv = venv.expanduser().absolute()
        if not public or venv.resolve() != Path(sys.prefix).resolve() or not commands_available(venv):
            if not checkout:
                raise ValueError("install agent-level in the target venv, activate it, then run agent-level setup")
            install_package(source, venv)
        if public and not commands_available(venv):
            raise ValueError("Agent Level commands are missing after installation; check this venv")
        enable_workspace(workspace, venv, source, instructions=instructions)
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"[error] setup failed: {exc}", file=sys.stderr)
        return 2
    print(f"[ok] installed and enabled in {workspace}")
    print("[next] View the report (no environment activation required):")
    print(f"  {report_command(workspace, venv)}")
    if public:
        print("[next] Start a new agent session. Trust a new Codex hook in /hooks before it runs.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
