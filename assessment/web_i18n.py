_PAIRS = sorted(TRANSLATIONS.items(), key=lambda pair: len(pair[0]), reverse=True)
_TEXT = re.compile(r'(?<=>)([^<>]+)(?=<)')


def english_html(chinese_html):
    """Translate rendered text nodes; leave tags, URLs, and JSON download untouched."""
    def translate(match):
        value = match.group(1)
        for source, target in _PAIRS:
            value = value.replace(source, target)
        return value

    result = _TEXT.sub(translate, chinese_html)
    return result.replace('aria-label="统计来源"', 'aria-label="Data source"')
