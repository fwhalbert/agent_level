def pair(message, **values):
    """Format both languages, translating only explicitly marked text values."""
    def render(template, index):
        return template.format(**{key: value[index] if isinstance(value, tuple) else value
                                  for key, value in values.items()}) if values else template
    return render(message, 0), render(ZH.get(message, message), 1)


def attributes(message, **values):
    en, zh = pair(message, **values)
    return f'data-en="{escape(en, quote=True)}" data-zh="{escape(zh, quote=True)}"'


def text(message, **values):
    en, _ = pair(message, **values)
    return f'<span {attributes(message, **values)}>{escape(en)}</span>'
